# Transcribes the numeric tables of the (LGPL) reference file refs/mobiclip.c into C# arrays.
import re,sys
src=open('refs/mobiclip.c',encoding='utf-8').read()
want={'zigzag4x4_tab':'byte','quant4x4_tab':'byte','quant8x8_tab':'byte','block4x4_coefficients_tab':'byte',
'pframe_block4x4_coefficients_tab':'byte','block8x8_coefficients_tab':'byte','pframe_block8x8_coefficients_tab':'byte',
'run_residue':'byte','bits0':'byte','syms0':'ushort','syms1':'ushort','mv_len':'byte','mv_bits':'byte','mv_syms':'byte'}
out=['// <auto-generated> by tools/gen_tables.py from interoperability data (see docs/PROVENANCE.md). Do not edit.','namespace Moflex.Core.Video;','','internal static class MobiclipTables','{']
for m in re.finditer(r'static const (\w+) (\w+)((?:\[[^\]]*\])+) =\s*\{(.*?)\n\};',src,re.S):
    name=m.group(2)
    if name not in want: continue
    nums=re.findall(r'0[xX][0-9A-Fa-f]+|\d+',m.group(4))
    vals=[str(int(n,0)) for n in nums]
    cname=''.join(p.capitalize() for p in name.split('_'))
    print(name,len(vals),file=sys.stderr)
    out.append(f'    public static readonly {want[name]}[] {cname} = {{')
    for i in range(0,len(vals),16): out.append('        '+', '.join(vals[i:i+16])+',')
    out.append('    };')
out.append('}')
open('src/Moflex.Core/Video/MobiclipTables.cs','w',encoding='utf-8').write('\n'.join(out)+'\n')
